"""Strict request and response contracts for sales workflow APIs."""
from datetime import datetime
from pydantic import BaseModel, ConfigDict, Field, field_validator
from app.models import SalesActivityType, SalesActivityOutcome, SalesPriority, SalesStatus


class SalesPatch(BaseModel):
    model_config = ConfigDict(extra="forbid")
    sales_status: SalesStatus | None = None
    priority: SalesPriority | None = None
    assigned_to: str | None = Field(default=None, max_length=120)
    next_follow_up_at: datetime | None = None
    lost_reason: str | None = Field(default=None, max_length=1000)

    @field_validator("assigned_to", "lost_reason")
    @classmethod
    def normalize_text(cls, value):
        if value is None:
            return value
        value = value.strip()
        return value or None

    @field_validator("next_follow_up_at")
    @classmethod
    def require_timezone(cls, value):
        if value is not None and value.tzinfo is None:
            raise ValueError("follow-up timestamp must include a timezone")
        return value


class SalesActivityCreate(BaseModel):
    model_config = ConfigDict(extra="forbid")
    activity_type: SalesActivityType
    note: str = Field(min_length=1, max_length=5000)
    outcome: SalesActivityOutcome | None = None

    @field_validator("activity_type")
    @classmethod
    def disallow_system_activity(cls, value):
        if value == SalesActivityType.STATUS_CHANGE:
            raise ValueError("STATUS_CHANGE activities are generated by sales status updates")
        return value

    @field_validator("note")
    @classmethod
    def trim_note(cls, value):
        value = value.strip()
        if not value:
            raise ValueError("note cannot be blank")
        return value


class SalesActivityOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: str
    lead_id: str
    activity_type: SalesActivityType
    occurred_at: datetime
    note: str
    outcome: SalesActivityOutcome | None = None
    suggested_task_type: str | None = None
    old_sales_status: SalesStatus | None = None
    new_sales_status: SalesStatus | None = None


class SalesOut(BaseModel):
    sales_status: SalesStatus
    priority: SalesPriority
    assigned_to: str | None
    next_follow_up_at: datetime | None
    lost_reason: str | None
    recent_activities: list[SalesActivityOut]
